export type LogoImageType = 'png' | 'jpeg' | 'webp';

/**
 * The REAL type of an image from its first bytes (magic numbers). The declared mime type and the file name are
 * never consulted. Only the three formats the logo pipeline accepts are recognised; everything else (SVG, GIF,
 * AVIF, TIFF, HEIC, text) is null.
 */
export function detectImageType(bytes: Uint8Array): LogoImageType | null {
  const b = bytes;
  if (
    b.length >= 8 &&
    b[0] === 0x89 &&
    b[1] === 0x50 &&
    b[2] === 0x4e &&
    b[3] === 0x47 &&
    b[4] === 0x0d &&
    b[5] === 0x0a &&
    b[6] === 0x1a &&
    b[7] === 0x0a
  )
    return 'png';
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'jpeg';
  // RIFF....WEBP
  if (
    b.length >= 12 &&
    b[0] === 0x52 &&
    b[1] === 0x49 &&
    b[2] === 0x46 &&
    b[3] === 0x46 &&
    b[8] === 0x57 &&
    b[9] === 0x45 &&
    b[10] === 0x42 &&
    b[11] === 0x50
  )
    return 'webp';
  return null;
}
